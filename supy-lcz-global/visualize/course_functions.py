def restructure_netatmo(net_file, grid_file, lcz_file, start_date, end_date, qc_level = 'o1'):

    ''' Restructure netatmo file to use in supy evaluation '''

    # Read the data
    print("Reading the data")
    df = pd.read_csv(net_file, index_col=0, parse_dates=True)

    print("Select qc-level and time range of interest")
    # Select the proper qc level
    df = df[df[qc_level] == True]

    # Select time range of interest
    df_sel = df.loc[start_date:end_date]

    # Get station information: id, lat, lon and altitude (z)
    df_stn = df_sel.drop_duplicates(subset='id', keep="first")[['p_id', 'lat', 'lon', 'z']]
    df_stn = df_stn.rename(columns={'p_id':'id'})

    print("Add SUEWS and LCZ grid labels to stations")
    # Add SUEWS and LCZ grid labels to stations
    gdf_stn = gpd.GeoDataFrame(
        df_stn, 
        geometry=gpd.points_from_xy(df_stn.lon, df_stn.lat)
        )
    gdf_stn.head()

    # Add SUPY gridID, via spatial join
    gdf_grid = gpd.read_file(grid_file)
    gdf_stn_new = gpd.tools.sjoin(gdf_stn, gdf_grid, how='left')

    # Clean-up a bit: remove columns, grid_id as index, and remove 
    # netatmo stations that fall outside of the SUEWS grid extent.
    gdf_stn_new.drop(['index_right'],axis=1, inplace=True)
    gdf_stn_new.rename(columns={
        'id_right':'grid_id',
        'id_left' :'netatmo_id',}, inplace=True)
    gdf_stn_new = gdf_stn_new[gdf_stn_new['grid_id'].notna()]
    gdf_stn_new = gdf_stn_new.set_index('grid_id')
    gdf_stn_new.index = gdf_stn_new.index.astype(int)

    # Also add LCZ class, from lczFilter layer
    lczData = xr.open_rasterio(f"{lcz_file}")
    LCZs = []
    for stn_i in range(gdf_stn_new.shape[0]):
        LCZ = int(lczData[0,:,:].sel(
            x=gdf_stn_new.iloc[stn_i]['lon'],
            y=gdf_stn_new.iloc[stn_i]['lat'],
            method="nearest").values)
        LCZs = LCZs + [LCZ]
    gdf_stn_new['LCZ'] = LCZs

    # Save to csv file
    net_stn_file = net_file.replace('netatmo_amsterdam_2019_QC', f'netatmo_qc_stn_{start_date}_{end_date}')
    gdf_stn_new.to_csv(net_stn_file)

    # Save to ESRI Shapfile
    gdf_stn_new.to_file(driver = 'ESRI Shapefile', 
                                filename = net_stn_file.replace('.csv','.shp'))

    print(f"The restructured Netatmo station file has been saved to:\n - {net_stn_file}\n - {net_stn_file.replace('.csv','.shp')}")

    # Select relevant observations, and rename
    # Only stations within domain
    df_sel_new = df_sel[df_sel['p_id'].isin(gdf_stn_new.netatmo_id)]

    # Set date without UTC
    df_sel_new['date'] = df_sel_new.index.tz_localize(None)

    # Select relevant variables
    df_obs = df_sel_new[['p_id', 'date', 'ta_int', 'max_temp','min_temp','humidity','max_humidity','min_humidity']]

    df_obs.rename(columns={
        "p_id":'id',
        "ta_int": "T2",
        "max_temp": "T2max",
        "min_temp": "T2min",
        "humidity": "RH2",
        "max_humidity": "RH2max",
        "min_humidity": "RH2min",
        }, inplace=True)

    # Save to file
    net_obs_file = net_file.replace('netatmo_amsterdam_2019_QC', f'netatmo_qc_obs_{start_date}_{end_date}')
    df_obs.to_csv(net_obs_file, index=None)

    print(
        f"The restructured Netatmo observation file has been saved to:\n - {net_obs_file}"
        )


def _get_color_schemes(scheme):
    '''helper function to get color schemes'''

    cb = {
        'lcz': [
            '#8c0000', '#d10000', '#ff0000', '#bf4d00',
            '#ff6600', '#ff9955', '#faee05', '#bcbcbc',
            '#ffccaa', '#555555', '#006a00', '#00aa00',
            '#648525', '#b9db79', '#000000', '#fbf7ae', '#6a6aff'],

        # 'Paved (-)', 'Buildings (-)', 'Grass (-)',
        # 'Deciduous trees (-)', 'Evergreen trees (-)', 'Bare soil (-)', 'Water (-)'
        'suews': [
            '#4d4d4d', '#d05e5e', '#c5f776',
            '#5ac18e', '#156475', '#99774d', '#6a6aff']
    }

    return cb[scheme]


def map_lcz_grid(grid_file, lcz_file,f_dir, net_stn_file):

    ''' Plot the LCZ map, the grid and grid ID numbers in figure '''

    # Define LCZ colors, make cmap
    cb_lcz = _get_color_schemes('lcz')
    
    cmap = mpl.colors.ListedColormap(cb_lcz)
    cmap.set_bad(color='white')
    cmap.set_under(color='white')

    # Read clipped LCZ map and grid
    lczTif = xr.open_rasterio(lcz_file)[0,:,:]
    gdf_grid = gpd.read_file(grid_file)

    # Initialize figures
    fig, ax = plt.subplots(figsize=(15, 10))

    # Add lcz map 
    im = lczTif.plot(
        cmap=cmap, vmin=1, vmax=17,
        ax=ax, add_colorbar=False,
    )

    cb_labels = np.arange(1,18,1)
    cb = plt.colorbar(
        im,
        ticks=np.linspace(1.5, 17-0.5, 17),
        orientation='horizontal', pad=0.08, shrink=0.8
    )
    cb.set_ticklabels(cb_labels)
    cb.set_label(label='LCZ Class', fontsize=11)
    cb.ax.tick_params(labelsize=11)

    gdf_grid.plot(ax=ax, facecolor='none', edgecolor='black')

    # Add grid cell numbers to map
    gdf_grid = gdf_grid.set_index("id")
    def getXY(pt):
        return (pt.x, pt.y)
    centroidseries = gdf_grid['geometry'].centroid
    lons,lats = [list(t) for t in zip(*map(getXY, centroidseries))]
    for i in range(len(lons)):
        ax.text(lons[i],lats[i],int(gdf_grid.index[i]),fontsize=13)
    
    # Add netatmo stations
    net_stn = pd.read_csv(net_stn_file,index_col=0)
    gdf_net_stn = gpd.GeoDataFrame(
        net_stn, 
        geometry=gpd.points_from_xy(net_stn.lon, net_stn.lat))
    gdf_net_stn.plot(marker="*",color="#e24afc", 
                     markersize=200, edgecolor='w', ax=ax)
        
    # Some axes aesthetics
    ax.tick_params(axis='both', which='major', labelsize=13)
    ax.set_xlabel('° Longitude', fontsize=13)
    ax.set_ylabel('° Latitude', fontsize=13)
    ax.set_title('')

    # Save to file
    plt.tight_layout()
    plt.savefig(f"{f_dir}/map_lcz_grid_netatmo.jpg",dpi=300)
    plt.close('all')
    

