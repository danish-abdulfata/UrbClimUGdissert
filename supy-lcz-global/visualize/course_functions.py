def plot_intra_suews_grid_variability(var, sub_start, sub_end,
                                      df_grid_suews, df_output, f_dir,
                                      vmin, vmax):
    
    '''Plot intra suews grid variability for suews variables'''
    
    plt.rcParams.update({'font.size': 14})
    x_ticks = np.arange(-0.05,1.1,0.1)
    
    # Prepare output data structure
    list_grid = pd.to_numeric(df_output.index.levels[0], downcast="integer")
    df_output.index = df_output.index.set_levels(list_grid, level=0)
    df_output = df_output.sort_index()

    # Get day and night based on Kdown from SUEWS output
    suews_kdown = df_output.loc[1,'Kdown'].loc[sub_start:sub_end]
    day_timesteps = suews_kdown[suews_kdown > 0].index
    night_timesteps = suews_kdown[suews_kdown == 0].index

    # Get imperviousness
    df_grid_suews['IMP'] = df_grid_suews['Paved (-)'] + df_grid_suews['Buildings (-)']

    # Initialize figure
    fig, ax = plt.subplots(1,3, figsize=(20,7), sharey=True)

    # Loop over bins of imperviousness
    for imp_i, imp in enumerate(np.arange(0,0.91,0.1)):

        grid_id_sel   = df_grid_suews['IMP'][(df_grid_suews['IMP'] >= imp) 
                                             & (df_grid_suews['IMP'] < imp+0.1)].index

        if len(grid_id_sel) != 0:

            suews_sel       = df_output.loc[grid_id_sel, [var]]\
                                    .droplevel('grid')\
                                    .loc[sub_start:sub_end]
            suews_sel_day   = suews_sel.loc[day_timesteps]
            suews_sel_night = suews_sel.loc[night_timesteps]

            # Plot all hour mean
            ax[0].errorbar(imp+0.05, suews_sel.mean().mean(), 
                           suews_sel.std().values[0],
                           linestyle='None', marker='o',lw=1, markersize=10,
                           color = '0.2')
            ax[0].set_title('Daily mean')
            ax[0].set_ylim(vmin,vmax)

            ax[0].text(np.linspace(0,1,12)[imp_i+1],0.95, str(len(grid_id_sel )),
                    verticalalignment='bottom', horizontalalignment='center',
                    transform=ax[0].transAxes,
                    color='purple', fontsize=12)

            # Plot day only mean
            ax[1].errorbar(imp+0.05, suews_sel_day.mean().mean(), 
                           suews_sel_day.std().values[0],
                           linestyle='None', marker='o',lw=1, markersize=10,
                           color = '0.2')
            ax[1].set_title('Day-time (Kdown > 0)')

            # Plot night only mean
            ax[2].errorbar(imp+0.05, suews_sel_night.mean().mean(), 
                           suews_sel_night.std().values[0],
                           linestyle='None', marker='o',lw=1, markersize=10,
                           color = '0.2')
            ax[2].set_title('Night-time (Kdown = 0)')

    for i in range(3):
        ax[i].set_xlabel('Imperviousness')
        ax[i].set_xticks(x_ticks)
        ax[i].set_xticklabels(np.around(np.arange(-0.05,1.1,0.1),2))
