def plot_intra_lcz_variability(var, sub_start, sub_end,
                               net_obs, net_stn, df_output, f_dir):
    
    '''Plot intra-lcz variability for netatmo stations'''
    
    plt.rcParams.update({'font.size': 14})
    
    # Get day and night based on Kdown from SUEWS output
    list_grid = pd.to_numeric(df_output.index.levels[0], downcast="integer")
    df_output.index = df_output.index.set_levels(list_grid, level=0)
    df_output = df_output.sort_index()
    suews_kdown = df_output.loc[1,'Kdown'].loc[sub_start:sub_end]

    day_timesteps = suews_kdown[suews_kdown > 0].index
    night_timesteps = suews_kdown[suews_kdown == 0].index

    # Initialize figure
    cb_lcz = _get_color_schemes('lcz')
    fig, ax = plt.subplots(1,3, figsize=(20,7), sharey=True)

    # Reduce netatmo to (sub-)period
    net_obs_sub = net_obs.loc[sub_start:sub_end]

    # Netatmo series contains missing timestamps. Clean up this dataframe.
    net_obs_clean = pd.pivot_table(net_obs_sub, values=var, index="date", columns="id")
    net_obs_clean = net_obs_clean.asfreq('1H')

    # Cross-check netatmo ID's with Obs ID's available for the selected period
    net_stn_cross = net_stn[net_stn.netatmo_id.isin(net_obs_clean.columns)]
    net_obs_clean = net_obs_clean[net_stn_cross.netatmo_id]


    # Loop over LCZ classes
    for lcz_i in range(1,18,1):

        lcz_net_id_sel = list(net_stn_cross[net_stn_cross.LCZ == lcz_i].netatmo_id)

        if len(lcz_net_id_sel) != 0:

            # Extract relevant netatmo data
            net_obs_sel = net_obs_clean[lcz_net_id_sel]
            net_obs_sel_day = net_obs_sel.loc[day_timesteps]
            net_obs_sel_night = net_obs_sel.loc[night_timesteps]

            # Plot all hour mean
            ax[0].errorbar(lcz_i, net_obs_sel.mean().mean(), 
                           net_obs_sel.std().std(),
                           linestyle='None', marker='o',lw=1, markersize=10,
                           color = cb_lcz[lcz_i-1])
            ax[0].set_title('Daily mean')

            ax[0].text(lcz_i/18, 0.02, str(len(lcz_net_id_sel)),
                    verticalalignment='bottom', horizontalalignment='center',
                    transform=ax[0].transAxes,
                    color='purple', fontsize=11)

            # Plot day only mean
            ax[1].errorbar(lcz_i, net_obs_sel_day.mean().mean(), 
                           net_obs_sel_day.std().std(),
                           linestyle='None', marker='o',lw=1, markersize=10,
                           color = cb_lcz[lcz_i-1])
            ax[1].set_title('Day-time (Kdown > 0)')

            # Plot night only mean
            ax[2].errorbar(lcz_i, net_obs_sel_night.mean().mean(), 
                           net_obs_sel_night.std().std(),
                           linestyle='None', marker='o',lw=1, markersize=10,
                           color = cb_lcz[lcz_i-1])
            ax[2].set_title('Night-time (Kdown = 0)')

    for i in range(3):
        ax[i].set_xlabel('LCZ Class')
        ax[i].set_xticks(range(0,19,1))
        ax[i].set_xticklabels(range(0,19,1))
        xticks = ax[i].xaxis.get_major_ticks()
        xticks[0].label1.set_visible(False)
        xticks[-1].label1.set_visible(False)
        ax[i].grid(ls='--',color='0.8',zorder=-10)

    ax[0].set_ylabel(var)

    plt.tight_layout()
    
    fig.savefig(os.path.join(
        f_dir,
        f"plot_intra_lcz_variability_{var}_{sub_start}_{sub_end}.jpg"),
                dpi = 300)
    

